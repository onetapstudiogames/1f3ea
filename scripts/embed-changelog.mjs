// Regenerate src/changelog-source.ts from the checked-in root CHANGELOG.md.
import { readFileSync, writeFileSync } from 'node:fs'

const escapeTemplate = value => value
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${')

const changelog = readFileSync('CHANGELOG.md', 'utf8')
const output = `// GENERATED by scripts/embed-changelog.mjs — edit CHANGELOG.md instead.\nexport const CHANGELOG_MARKDOWN = \`${escapeTemplate(changelog)}\`\n`
if (process.argv.includes('--check')) {
  if (readFileSync('src/changelog-source.ts', 'utf8') !== output)
    throw new Error('generated changelog source is stale')
  console.log('changelog source matches CHANGELOG.md')
} else {
  writeFileSync('src/changelog-source.ts', output)
  console.log('src/changelog-source.ts regenerated')
}
